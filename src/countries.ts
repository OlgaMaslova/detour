/**
 * `<option>` markup for a country `<select>`. The first option is an empty
 * "no answer" choice, since supplying a home country is optional. `selected`
 * pre-selects a prior value (member profile edits), including one that predates
 * the current list.
 */
export function countryOptions(selected = ''): string {
  const known = COUNTRIES.includes(selected);
  const rows = [`<option value="">Prefer not to say</option>`];
  if (selected && !known) {
    rows.push(`<option value="${escapeAttr(selected)}" selected>${escapeAttr(selected)}</option>`);
  }
  for (const country of COUNTRIES) {
    const isSelected = known && country === selected ? ' selected' : '';
    rows.push(`<option value="${escapeAttr(country)}"${isSelected}>${escapeAttr(country)}</option>`);
  }
  return rows.join('');
}

function escapeAttr(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
